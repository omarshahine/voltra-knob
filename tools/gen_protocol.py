def crc8(b):
    c = 0x77
    for x in b: c = CRC8_TABLE[c ^ x]
    return c

def crc16(b):
    c = 0x3692
    for x in b: c = ((c >> 8) & 0xff) ^ CRC16_TABLE[(c & 0xff) ^ x]
    return c

def with_checksums(frame):
    f = bytearray(frame)
    f[3] = crc8(f[0:3])
    c = crc16(f[:-2])
    f[-2] = c & 0xff; f[-1] = (c >> 8) & 0xff
    return bytes(f)

def auth_with_name(template_hex, name):
    """The auth frame carries a NUL-padded device name after the cmd byte at index 10.
    The two SDK frames (iPhone / iPad) differ only in that field and the CRC, which fixes its bounds."""
    t = bytes.fromhex(template_hex)
    if with_checksums(t) != t: sys.exit("CRC port does not reproduce the SDK auth frame")
    name_start = 11
    field_len = 21  # bytes 11..31 inclusive; the 7-byte trailer begins at 32 (cmd 0x4f at byte 10 = deviceName)
    trailer = t[name_start + field_len:-2]
    enc = name.encode("ascii")
    if len(enc) > field_len: sys.exit("auth name too long")
    body = t[:name_start] + enc.ljust(field_len, b"\x00") + trailer + b"\x00\x00"
    return with_checksums(body)

def param_read_frame(param_ids):
    """cmd 0x0f: read parameters. Mirrors the SDK's buildGuidedLoadStatusReadFrame envelope."""
    payload = bytes([len(param_ids) & 0xff, (len(param_ids) >> 8) & 0xff]) + b"".join(param_ids)
    total = 13 + len(payload)
    f = bytearray(total)
    f[0] = 0x55; f[1] = total; f[2] = 0x04
    f[4] = 0xaa; f[5] = 0x10; f[6] = 0x00; f[7] = 0x20; f[8] = 0x20; f[9] = 0x00
    f[10] = 0x0f
    f[11:11 + len(payload)] = payload
    return with_checksums(bytes(f))

def vendor_frame(payload):
    """cmd 0xaa vendor frame with the standard app->device envelope (SDK buildGuidedLoadTriggerFrame)."""
    total = 11 + len(payload) + 2
    f = bytearray(total)
    f[0] = 0x55; f[1] = total; f[2] = 0x04
    f[4] = 0xaa; f[5] = 0x10; f[6] = 0x00; f[7] = 0x20; f[8] = 0x20; f[9] = 0x00
    f[10] = 0xaa
    f[11:11 + len(payload)] = payload
    return with_checksums(bytes(f))

def arr(name, hexstr):
    b = bytes.fromhex(hexstr)
    if b[0] != 0x55 or b[1] != len(b):
        sys.exit(f"{name}: bad frame header/length {hexstr}")
    body = ", ".join(f"0x{x:02x}" for x in b)
    return f"constexpr uint8_t {name}[{len(b)}] = {{{body}}};\n"

